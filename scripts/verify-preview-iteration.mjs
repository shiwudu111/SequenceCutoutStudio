import path from 'node:path'
import fs from 'node:fs/promises'
import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import { fileURLToPath } from 'node:url'
import { execFileSync } from 'node:child_process'

const require = createRequire(import.meta.url)
const { _electron } = require(process.env.SCS_PLAYWRIGHT_MODULE || 'playwright')
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const output = path.join(root, 'release', 'preview-iteration-check')
await fs.mkdir(output, { recursive: true })
execFileSync(path.join(root, 'portable-root/tools/ffmpeg/ffmpeg.exe'), [
  '-y', '-f', 'lavfi', '-i', 'color=c=red:s=64x64:r=4', '-t', '1',
  '-pix_fmt', 'yuv420p', path.join(output, 'sample.mp4')
], { windowsHide: true, stdio: 'pipe' })
const env = { ...process.env }
delete env.ELECTRON_RUN_AS_NODE
const app = await _electron.launch({ executablePath: path.join(root, 'node_modules/electron/dist/electron.exe'),
  args: [root], cwd: root, env })
const checks = []
try {
  const page = await app.firstWindow()
  const errors = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.waitForSelector('.preview-stage')
  const setDialog = async (filePath) => app.evaluate(({ dialog }, file) => {
    dialog.showOpenDialog = async (options) => {
      globalThis.testDialogOptions = options
      return { canceled: false, filePaths: [file] }
    }
  }, filePath)
  await setDialog(path.join(output, 'sample.gif'))
  await page.getByRole('button', { name: '选择视频', exact: true }).click()
  assert((await app.evaluate(() => globalThis.testDialogOptions)).filters[0].extensions.includes('gif'))
  assert(await page.locator('.video-field-grid input').nth(0).isDisabled())
  assert(await page.locator('.video-field-grid input').nth(1).isDisabled())
  await page.getByRole('button', { name: '切成序列帧', exact: true }).click()
  await page.waitForFunction(() => document.querySelector('.playback-status')?.textContent.includes('/ 4'))
  // Recover the output through the real scan API and the known extraction directory.
  const candidates = (await fs.readdir(output)).filter((name) => name.startsWith('sample_gif_'))
  const extracted = path.join(output, candidates.sort().at(-1))
  const scan = await page.evaluate((folder) => window.cutoutAPI.scanFrameFolder(folder), extracted)
  assert.deepEqual(scan.frameDurationsMs, [50, 120, 200, 80])
  assert.equal(scan.files.length, 4)
  checks.push('GIF file dialog, disabled FPS/duration, real extraction and timing scan')

  await page.getByLabel('区间循环', { exact: true }).check()
  await page.getByLabel('起始帧', { exact: true }).fill('2')
  await page.getByLabel('结束帧', { exact: true }).fill('3')
  await page.getByRole('button', { name: '播放', exact: true }).click()
  await page.waitForTimeout(400)
  const observed = []
  for (let i = 0; i < 12; i++) {
    observed.push(Number((await page.locator('.playback-status').textContent()).match(/· (\d+) \/ /)[1]))
    await page.waitForTimeout(50)
  }
  assert(observed.every((frame) => frame === 2 || frame === 3), JSON.stringify(observed))
  assert(observed.includes(2) && observed.includes(3))
  await page.getByRole('button', { name: '暂停', exact: true }).click()
  await page.getByLabel('结束帧', { exact: true }).fill('2')
  await page.getByRole('button', { name: '播放', exact: true }).click()
  await page.waitForTimeout(450)
  assert.match(await page.locator('.playback-status').textContent(), /· 2 \/ 4/)
  await page.getByRole('button', { name: '暂停', exact: true }).click()
  checks.push('Range 2-3 loops; single-frame range remains valid')

  await page.locator('.preview-stage img').first().dblclick()
  const box = page.locator('.preview-lightbox')
  const image = box.locator('img')
  const backgroundSelect = box.getByRole('combobox', { name: '放大预览背景', exact: true })
  const toolbar = box.locator('.preview-lightbox-toolbar')
  const toolbarStyle = () => toolbar.evaluate((el) => {
    const css = getComputedStyle(el)
    return { background: css.backgroundColor, padding: css.padding, height: el.getBoundingClientRect().height }
  })
  assert(await backgroundSelect.isDisabled())
  const defaultToolbar = await toolbarStyle()
  assert.equal(await page.getByLabel('使用主预览背景', { exact: true }).isChecked(), false)
  const originalBackground = await box.evaluate((el) => getComputedStyle(el).backgroundColor)
  const scrollState = () => page.evaluate(() => [window.scrollY, ...Array.from(document.querySelectorAll('*')).filter((el) => el.scrollTop > 0).map((el) => [el.className, el.scrollTop])])
  const before = await scrollState()
  await image.hover()
  await page.mouse.wheel(0, -180)
  await page.waitForTimeout(150)
  assert.deepEqual(await scrollState(), before)
  assert.match(await image.getAttribute('style'), /scale\(1.15\)/)
  const bounds = await image.boundingBox()
  await page.mouse.move(bounds.x + bounds.width / 2, bounds.y + bounds.height / 2)
  await page.mouse.down()
  await page.mouse.move(bounds.x + bounds.width / 2 + 30, bounds.y + bounds.height / 2 + 20)
  await page.mouse.up()
  const transform = await image.getAttribute('style')
  await page.getByLabel('使用主预览背景', { exact: true }).check()
  assert.equal(await backgroundSelect.isDisabled(), false)
  assert.deepEqual(await toolbarStyle(), defaultToolbar)
  assert.equal(await box.getByRole('button', { name: '棋盘', exact: true }).count(), 0)
  await backgroundSelect.selectOption('white')
  assert.equal(await box.evaluate((el) => getComputedStyle(el).backgroundColor), 'rgb(255, 255, 255)')
  assert.equal(await image.getAttribute('style'), transform)
  await setDialog(path.join(extracted, 'sample_0001.png'))
  await backgroundSelect.selectOption('choose-image')
  await page.waitForFunction(() => document.querySelector('.preview-lightbox')?.classList.contains('custom'))
  assert.match(await box.evaluate((el) => getComputedStyle(el).backgroundImage), /data:image/)
  assert.equal(await box.evaluate((el) => getComputedStyle(el).backgroundSize), 'auto')
  assert.equal(await image.getAttribute('style'), transform)
  await page.getByLabel('使用主预览背景', { exact: true }).uncheck()
  assert.equal(await box.evaluate((el) => getComputedStyle(el).backgroundColor), originalBackground)
  assert.equal(await image.getAttribute('style'), transform)
  await page.getByLabel('使用主预览背景', { exact: true }).check()
  await backgroundSelect.selectOption('checker')
  await page.screenshot({ path: path.join(output, 'lightbox.png') })
  for (const [width, height] of [[1440, 1000], [920, 640]]) {
    await app.evaluate(({ BrowserWindow }, size) => BrowserWindow.getAllWindows()[0].setSize(...size), [width, height])
    const enabledStyle = await toolbarStyle()
    assert(await toolbar.evaluate((el) => el.scrollWidth <= el.clientWidth))
    await page.screenshot({ path: path.join(output, `lightbox-toolbar-${width}-enabled.png`) })
    await page.getByLabel('使用主预览背景', { exact: true }).uncheck()
    assert.deepEqual(await toolbarStyle(), enabledStyle)
    await page.screenshot({ path: path.join(output, `lightbox-toolbar-${width}-default.png`) })
    await page.getByLabel('使用主预览背景', { exact: true }).check()
  }
  checks.push('Lightbox toolbar stays identical when toggled; background dropdown; no overflow at 1440/920')
  await page.keyboard.press('Escape')
  assert.equal(await page.evaluate(() => document.body.style.overflow), '')
  checks.push('Lightbox default, wheel scroll isolation, drag, optional background, restore and Escape')

  await page.getByLabel('区间循环', { exact: true }).uncheck()
  await page.getByLabel('原始节奏', { exact: true }).uncheck()
  await page.getByLabel('播放 FPS', { exact: true }).fill('12')
  await page.getByRole('button', { name: '播放', exact: true }).click()
  await page.waitForTimeout(300)
  await page.locator('.preview-stage img').first().dblclick()
  assert.equal(await page.getByLabel('使用主预览背景', { exact: true }).isChecked(), false)
  const firstSrc = await image.getAttribute('src')
  await page.waitForFunction((src) => document.querySelector('.preview-lightbox img')?.getAttribute('src') !== src, firstSrc)
  assert.match(await page.locator('.playback-status').textContent(), /播放中/)
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: '暂停', exact: true }).click()
  checks.push('Full range restore, manual FPS, playback continues when toggling lightbox background')

  for (const [width, height] of [[1440, 1000], [1024, 768], [920, 640]]) {
    await app.evaluate(({ BrowserWindow }, size) => BrowserWindow.getAllWindows()[0].setSize(...size), [width, height])
    await page.locator('.playback-controls').scrollIntoViewIfNeeded()
    await page.screenshot({ path: path.join(output, `preview-${width}.png`) })
    assert(await page.locator('.playback-controls').evaluate((el) => el.scrollWidth <= el.clientWidth), `overflow at ${width}`)
  }
  await setDialog(extracted)
  await page.getByRole('button', { name: '选择序列帧文件夹', exact: true }).click()
  await page.waitForTimeout(400)
  assert.equal(await page.getByLabel('区间循环', { exact: true }).isChecked(), false)
  assert.equal(await page.getByLabel('结束帧', { exact: true }).inputValue(), '4')
  await setDialog(path.join(output, 'sample.mp4'))
  await page.getByRole('button', { name: '选择视频', exact: true }).click()
  assert.equal(await page.locator('.video-field-grid input').nth(0).isDisabled(), false)
  assert.equal(await page.locator('.video-field-grid input').nth(1).isDisabled(), false)
  await page.locator('.video-field-grid input').nth(0).fill('4')
  await page.locator('.video-field-grid input').nth(1).fill('1')
  await page.getByRole('button', { name: '切成序列帧', exact: true }).click()
  await page.waitForFunction(() => document.querySelector('.playback-status')?.textContent.includes('/ 4'))
  assert.equal(await page.getByLabel('原始节奏', { exact: true }).count(), 0)
  checks.push('Desktop sizes, source reset, video controls restored')
  const rangeFixture = path.join(output, 'range-20')
  await fs.mkdir(rangeFixture, { recursive: true })
  for (let i = 1; i <= 20; i++) {
    await fs.copyFile(path.join(extracted, `sample_${String((i - 1) % 4 + 1).padStart(4, '0')}.png`),
      path.join(rangeFixture, `frame_${String(i).padStart(4, '0')}.png`))
  }
  await setDialog(rangeFixture)
  await page.getByRole('button', { name: '选择序列帧文件夹', exact: true }).click()
  await page.waitForFunction(() => document.querySelector('.playback-status')?.textContent.includes('/ 20'))
  await page.getByLabel('区间循环', { exact: true }).check()
  const start = page.getByLabel('起始帧', { exact: true })
  const end = page.getByLabel('结束帧', { exact: true })
  await start.fill('5')
  await start.press('Tab')
  await end.fill('')
  await end.pressSequentially('14', { delay: 100 })
  assert.equal(await end.inputValue(), '14')
  await end.press('Enter')
  assert.match(await page.locator('.playback-status').textContent(), /5-14 循环/)
  await end.fill('')
  await end.press('Tab')
  assert.equal(await end.inputValue(), '14')
  await end.fill('99')
  await end.press('Enter')
  assert.equal(await end.inputValue(), '20')
  await start.fill('')
  await start.pressSequentially('12', { delay: 100 })
  await start.press('Tab')
  assert.equal(await start.inputValue(), '12')
  await end.fill('2')
  await end.press('Enter')
  assert.equal(await end.inputValue(), '12')
  checks.push('Sequential numeric entry 5-14, empty restore, upper/lower bounds, background auto sizing and reopen reset')

  const webpCases = [{ source: path.join(output, 'sample.webp'), count: 4, durations: [30, 70, 110, 190] }]
  if (process.env.SCS_WEBP_SAMPLE) {
    const source = path.join(output, 'user-sample.WEBP')
    await fs.copyFile(process.env.SCS_WEBP_SAMPLE, source)
    const report = JSON.parse(await fs.readFile(path.join(output, 'webp-verification.json'), 'utf8'))
    webpCases.push({ source, count: report.frames.length, durations: report.frames.map((f) => f.durationMs) })
  }
  for (const fixture of webpCases) {
    const originalBytes = await fs.readFile(fixture.source)
    const dropped = await page.evaluate((file) => window.cutoutAPI.resolveDroppedPath(file), fixture.source)
    assert.equal(dropped.kind, 'video')
    await setDialog(fixture.source)
    await page.getByRole('button', { name: '选择视频', exact: true }).click()
    assert((await app.evaluate(() => globalThis.testDialogOptions)).filters[0].extensions.includes('webp'))
    assert(await page.locator('.video-field-grid input').nth(0).isDisabled())
    assert(await page.locator('.video-field-grid input').nth(1).isDisabled())
    const previous = new Set(await fs.readdir(output))
    await page.getByRole('button', { name: '切成序列帧', exact: true }).click()
    await page.waitForFunction((count) => document.querySelector('.playback-status')?.textContent.includes(`/ ${count}`), fixture.count)
    const newDir = (await fs.readdir(output)).find((name) => !previous.has(name) && name.includes('_webp_'))
    assert(newDir)
    const folder = path.join(output, newDir)
    const webpScan = await page.evaluate((dir) => window.cutoutAPI.scanFrameFolder(dir), folder)
    assert.deepEqual(webpScan.frameDurationsMs, fixture.durations)
    assert.equal(webpScan.pngCount, fixture.count)
    assert.equal(webpScan.hasAlpha, true)
    assert(await page.getByLabel('原始节奏', { exact: true }).isChecked())
    assert(await page.getByLabel('播放 FPS', { exact: true }).isDisabled())
    const firstSrc = await page.locator('.preview-stage img').first().getAttribute('src')
    await page.getByRole('button', { name: '播放', exact: true }).click()
    await page.waitForFunction((src) => document.querySelector('.preview-stage img')?.getAttribute('src') !== src, firstSrc)
    await page.getByRole('button', { name: '暂停', exact: true }).click()
    await page.getByLabel('原始节奏', { exact: true }).uncheck()
    assert.equal(await page.getByLabel('播放 FPS', { exact: true }).isDisabled(), false)
    await page.locator('.preview-stage img').first().dblclick()
    await page.getByLabel('使用主预览背景', { exact: true }).check()
    for (const [name, value] of [['棋盘', 'checker'], ['白', 'white'], ['黑', 'black']]) {
      await backgroundSelect.selectOption(value)
      await page.screenshot({ path: path.join(output, `${path.basename(fixture.source)}-${name}.png`) })
    }
    await page.keyboard.press('Escape')
    const repeated = await page.evaluate((videoPath) => window.cutoutAPI.extractVideoFrames({
      videoPath, fps: 1, durationSeconds: 0.01, outputPrefix: 'repeat'
    }), fixture.source)
    assert.equal(repeated.ok, true)
    assert.equal(repeated.outputCount, fixture.count)
    assert.notEqual(repeated.outputDir, folder)
    assert.deepEqual(await fs.readFile(fixture.source), originalBytes)
    await setDialog(folder)
    await page.getByRole('button', { name: '选择序列帧文件夹', exact: true }).click()
    await page.waitForFunction(() => document.querySelector('.preview-check input')?.checked)
    assert(await page.getByLabel('原始节奏', { exact: true }).isChecked())
    checks.push(`WebP ${path.basename(fixture.source)}: import, drop recognition, ${fixture.count} frames, timing, alpha, playback, backgrounds, repeat protection and reopen`)
  }
  await setDialog(path.join(output, 'sample.mp4'))
  await page.getByRole('button', { name: '选择视频', exact: true }).click()
  assert.equal(await page.locator('.video-field-grid input').nth(0).isDisabled(), false)
  assert.equal(await page.locator('.video-field-grid input').nth(1).isDisabled(), false)
  // Existing src/main.tsx calls window.ipcRenderer.on although preload exposes cutoutAPI only.
  const knownBaselineErrors = errors.filter((message) => message === "Cannot read properties of undefined (reading 'on')")
  const unexpectedErrors = errors.filter((message) => !knownBaselineErrors.includes(message))
  assert.deepEqual(unexpectedErrors, [])
  console.log(JSON.stringify({ checks, knownBaselineErrors, unexpectedErrors }, null, 2))
  await fs.writeFile(path.join(output, 'verification.json'), JSON.stringify({ checks, knownBaselineErrors, unexpectedErrors }, null, 2))
} finally {
  await app.close()
}
